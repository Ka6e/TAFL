namespace Runtime;
public enum ValueType
{
    /// <summary>
    /// Значение отсутствует.
    /// </summary>
    Void,

    /// <summary>
    /// Числовое значение.
    /// </summary>
    Int,

    /// <summary>
    /// Строковое значение.
    /// </summary>
    String,

    /// <summary>
    /// Вещественное значение.
    /// </summary>
    Float,

    /// <summary>
    /// Булевое значение.
    /// </summary>
    Bool,
}
